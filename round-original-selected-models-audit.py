MODULES = ['Hindman168/NativeSubprobApproximation.lean', 'Hindman168/NativeSubprobSelectedModels.lean', 'Hindman168/OriginalMasterSelectedModels.lean', 'Hindman168/MasterGapIndex.lean']
COMPONENTS = ['Native clipped approximation and all-padding selected models now hold for every original nonnegative law of total mass at most one. All projection and distance calculations retain the original Hilbert spaces.', 'Actual original master pivot masses are substituted in selected-model selection, removing all-stage probability normalization and nonnegativity premises from its conclusion interface. The master Ramsey bound is fixed before the master family, ultrafilter, gap maps and target families.', 'The canonical finite master gap map is monotone everywhere and exactly equal to the original index within range. Its gap divisibility is proved directly from MasterParameterConditions, preparing the concrete finite-master instantiation.']
